interface ProjectSetSpec {
  id: string;
  title: string;
  description: string;
  root: string;
  composition: string;
  projects: string[];
  /** Directed edges between projects, as `[source, target]` pairs. */
  edges: [string, string][];
  shapes: Record<string, ModelShape>;
  /** Optional override for a claim's title, so a fixture can force long wrapped labels. */
  titleFor?: (source: string, target: string) => string;
}

/** A small directed project graph with exactly the listed claims. */
function projectSet(spec: ProjectSetSpec): GeneratedFixtureSources {
  const all = [spec.root, ...spec.projects];
  const models: FixtureModel[] = all.map((model) => {
    const shape = spec.shapes[model];
    const foreign = all.filter((other) => other !== model);
    const outgoing = spec.edges.filter(([source]) => source === model);
    const outgoingTargets = new Set(outgoing.map(([, target]) => target));
    const links = foreign
      .filter((other) => outgoingTargets.has(other) || (model === spec.root && other !== spec.root))
      .map((other) => link(`link-${other}`, other, 'g0'));
    const connections = outgoing.map(([, target], index) =>
      connection(
        `call-${index}`,
        model,
        'g0',
        target,
        'g0',
        spec.titleFor ? spec.titleFor(model, target) : `${model} calls ${target}`
      )
    );
    if (model === spec.root)
      return rootModel(
        model,
        shape.title,
        linksFile(links, connections, [
          {
            id: spec.composition,
            title: spec.title,
            rootScene: 'overview',
            projects: spec.projects.map((other) => ({
              model: other,
              scene: 'overview',
              mode: 'open' as const
            }))
          }
        ])
      );
    return { ...modelSource(shape), links: linksFile(links, connections) };
  });
  return {
    fixtures: [
      {
        id: spec.id,
        title: spec.title,
        description: spec.description,
        root: spec.root,
        composition: spec.composition
      }
    ],
    models
  };
}

