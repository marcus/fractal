function modelSource(shape: ModelShape): FixtureModel {
  const lines = [
    'specification {',
    '  element group',
    '  element component',
    '  relationship calls',
    '}',
    'model {'
  ];
  const container = (group: number): string =>
    shape.longTitles
      ? `${shape.title} operational subsystem number ${group + 1} with a deliberately long authored name`
      : `Group ${group + 1}`;
  for (let g = 0; g < shape.groups; g++) {
    lines.push(`  g${g} = group '${container(g)}' {`);
    lines.push(`    metadata { uid 'g${g}' }`);
    for (let c = 0; c < shape.perGroup; c++) {
      const child = shape.longTitles
        ? `Component ${g + 1}.${c + 1} whose descriptive title runs well past a comfortable card width`
        : `Component ${g + 1}.${c + 1}`;
      lines.push(`    c${c} = component '${child}' { metadata { uid 'g${g}.c${c}' } }`);
    }
    lines.push('  }');
  }
  const total = shape.groups * shape.perGroup;
  const seen = new Set<string>();
  const pushRelationship = (a: number, b: number, index: number): void => {
    const ga = Math.floor(a / shape.perGroup);
    const ca = a % shape.perGroup;
    const gb = Math.floor(b / shape.perGroup);
    const cb = b % shape.perGroup;
    lines.push(
      `  g${ga}.c${ca} -[calls]-> g${gb}.c${cb} 'Calls ${index + 1}' { metadata { uid 'r${index}' } }`
    );
  };
  if (shape.relationshipFamilies !== undefined) {
    // Deterministic dense edges: family `f` gives every child one edge to `a * (7 + 4f) + 1`.
    let index = 0;
    for (let family = 0; family < shape.relationshipFamilies && total > 1; family++) {
      const step = 7 + family * 4;
      for (let a = 0; a < total; a++) {
        const b = (a * step + 1) % total;
        if (a === b) continue;
        const pair = `${a}->${b}`;
        if (seen.has(pair)) continue;
        seen.add(pair);
        pushRelationship(a, b, index++);
      }
    }
  } else {
    for (let i = 0; i < shape.relationships && total > 1; i++) {
      const a = (i * 3) % total;
      let b = (i * 7 + 1) % total;
      if (a === b) b = (b + 1) % total;
      if (a === b) continue;
      const pair = `${a}->${b}`;
      if (seen.has(pair)) continue;
      seen.add(pair);
      pushRelationship(a, b, i);
    }
  }
  lines.push('}');
  const groups = Array.from({ length: shape.groups }, (_value, g) => `g${g}`);
  const boundaries = shape.trust
    ? [
        {
          id: 'trust-core',
          title: 'Shared build trust',
          description: 'Overlaps the runtime trust set on purpose.',
          kind: 'permission',
          members: [groupChild(0, 0), groupChild(1, 0), groupChild(2, 0)],
          color: '#739886'
        },
        {
          id: 'trust-runtime',
          title: 'Runtime permissions',
          description: 'Overlaps the shared build trust set on purpose.',
          kind: 'permission',
          members: [groupChild(1, 0), groupChild(2, 0), groupChild(0, 1)],
          color: '#82A6B6'
        },
        {
          id: 'trust-audit',
          title: 'Audit visibility',
          description: 'Overlaps both other membership claims.',
          kind: 'permission',
          members: [groupChild(2, 0), groupChild(0, 0), groupChild(1, 1)],
          color: '#B59669'
        }
      ]
    : [];
  const companion = {
    version: 1,
    id: shape.id,
    title: shape.title,
    description: shape.description,
    provenance,
    boundaries,
    scenes: [
      {
        id: 'overview',
        title: 'Overview',
        description: shape.description,
        expanded: groups,
        proposed: false,
        lens: shape.trust ? 'trust' : 'structure'
      }
    ]
  };
  return { id: shape.id, model: `${lines.join('\n')}\n`, companion, links: null };
}

function groupChild(group: number, child: number): string {
  return `g${group}.c${child}`;
}

/** Every element UID of a generated shape, containers first, in declaration order. */
export function elementIds(shape: ModelShape): string[] {
  const ids: string[] = [];
  for (let g = 0; g < shape.groups; g++) {
    ids.push(`g${g}`);
    for (let c = 0; c < shape.perGroup; c++) ids.push(groupChild(g, c));
  }
  return ids;
}

function linksFile(
  links: LinkEntry[],
  connections: ConnectionEntry[] = [],
  compositions: CompositionEntry[] = []
): LinksFile {
  return { version: 1, links, connections, compositions };
}

function link(id: string, target: string, from?: string): LinkEntry {
  return { id, ...(from === undefined ? {} : { from }), target: { model: target }, title: target };
}

function connection(
  id: string,
  source: string,
  sourceElement: string,
  target: string,
  targetElement: string,
  title: string,
  kind = 'calls'
): ConnectionEntry {
  return {
    id,
    source: { model: source, element: sourceElement },
    target: { model: target, element: targetElement },
    title,
    kind,
    status: 'current',
    description: `Generated ${kind} claim from ${source} to ${target}.`,
    evidence: [`src/${source}.ts`]
  };
}

const ROOT_SHAPE: Omit<ModelShape, 'id' | 'title' | 'description'> = {
  groups: 2,
  perGroup: 1,
  relationships: 1
};

function rootModel(id: string, title: string, links: LinksFile): FixtureModel {
  const model = modelSource({ id, title, description: `${title} benchmark root.`, ...ROOT_SHAPE });
  return { ...model, links };
}

