interface CompositionPass {
  durations: Record<CompositionStage, number>;
  composed: ComposedDiagram;
  snapshots: ProjectSnapshot[];
  bytes: number;
  engine: BenchEngineId;
}

const round = (value: number, places: number): number => {
  const factor = 10 ** places;
  return Math.round(value * factor) / factor;
};

function summarize(
  runs: readonly CompositionPass[]
): Partial<Record<CompositionStage, StageStats>> {
  const stages: Partial<Record<CompositionStage, StageStats>> = {};
  for (const stage of COMPOSITION_STAGES) {
    const samples = runs.map((run) => run.durations[stage]);
    if (!samples.length) continue;
    stages[stage] = {
      p50: round(percentile(samples, 0.5), 3),
      p95: round(percentile(samples, 0.95), 3),
      samples: samples.length
    };
  }
  return stages;
}

/** One full composition pass: catalog resolution, parse, local layout, place/route and serialize. */
async function compositionPass(
  root: string,
  composition: string,
  participating: string[],
  catalog: CatalogOptions
): Promise<CompositionPass> {
  const durations: Record<CompositionStage, number> = {
    resolve: 0,
    parse: 0,
    local: 0,
    compose: 0,
    place: 0,
    serialize: 0
  };
  const directories = new Map<string, string>();
  let start = performance.now();
  for (const model of participating)
    directories.set(model, (await resolveProject(model, catalog)).entry.directory);
  durations.resolve = performance.now() - start;

  const snapshots = new Map<string, ProjectSnapshot>();
  start = performance.now();
  for (const model of participating)
    snapshots.set(model, snapshotOf(await loadDirectory(directories.get(model)!)));
  durations.parse = performance.now() - start;

  const rootSnapshot = snapshots.get(root)!;
  const state = stateFromComposition(rootSnapshot, composition, (model) => snapshots.get(model));
  start = performance.now();
  for (const project of state.projects) {
    if (project.mode === 'collapsed') continue;
    const snapshot = snapshots.get(project.model)!;
    await layout(snapshot.model, {
      ...project.view,
      theme: state.theme,
      layout: state.layout
    });
  }
  durations.local = performance.now() - start;

  start = performance.now();
  const composed = await compose(staticResolver(snapshots.values()), state);
  durations.compose = performance.now() - start;
  // `compose` runs local layout again; subtract the local pass just measured so `place` reports
  // frame placement and bridge routing only. Splitting those two apart needs an internal seam the
  // composition core does not expose yet.
  durations.place = Math.max(0, durations.compose - durations.local);

  start = performance.now();
  const json = JSON.stringify(composed);
  durations.serialize = performance.now() - start;

  return {
    durations,
    composed,
    snapshots: [...snapshots.values()],
    bytes: Buffer.byteLength(json),
    engine: state.layout
  };
}

/**
 * Measure one composition: a cold parse sample after clearing the model cache, one discardable
 * warm-up, then `iterations` timed passes. Resolution, parse, local layout, placement/routing and
 * serialization are timed separately; counts, bytes and a deterministic geometry fingerprint are
 * reported. Measured `parse` passes are warm stamp lookups, exactly like the single-model bench's
 * `load`; the cold sample is the separate cold evidence.
 */
export async function measureComposition(
  options: MeasureCompositionOptions
): Promise<CompositionRun> {
  if (!Number.isInteger(options.iterations) || options.iterations < 1)
    throw new Error('Iterations must be a whole number of at least 1');
  const catalog: CatalogOptions = { catalog: options.catalog };
  const rootOutcome = await catalogResolver(catalog).resolve(options.root);
  if (rootOutcome.status !== 'resolved')
    throw new Error(`Root ${options.root} could not be resolved: ${rootOutcome.message}`);
  const authored = rootOutcome.snapshot.links?.compositions.find(
    (candidate) => candidate.id === options.composition
  );
  if (!authored) throw new Error(`Unknown composition: ${options.composition} in ${options.root}`);
  const participating = [options.root, ...authored.projects.map((project) => project.model)].filter(
    (model, index, all) => all.indexOf(model) === index
  );

  clearModelCache();
  const coldStart = performance.now();
  for (const model of participating)
    await loadDirectory((await resolveProject(model, catalog)).entry.directory);
  const coldParseMs = performance.now() - coldStart;

  await compositionPass(options.root, options.composition, participating, catalog);
  const runs: CompositionPass[] = [];
  for (let i = 0; i < options.iterations; i++)
    runs.push(await compositionPass(options.root, options.composition, participating, catalog));
  const last = runs[runs.length - 1];
  const cache = modelCacheStats();
  const open = last.composed.projects.filter((project) => project.diagram !== null);
  const counts: CompositionCounts = {
    projects: last.composed.projects.length,
    loadedElements: last.snapshots.reduce(
      (total, snapshot) => total + snapshot.model.elements.length,
      0
    ),
    loadedRelationships: last.snapshots.reduce(
      (total, snapshot) => total + snapshot.model.relationships.length,
      0
    ),
    visibleNodes: open.reduce((total, project) => total + project.diagram!.nodes.length, 0),
    visibleEdges: open.reduce((total, project) => total + project.diagram!.edges.length, 0),
    bridges: last.composed.bridges.length,
    stubs: last.composed.stubs.length,
    diagnostics: last.composed.diagnostics.length,
    cacheHits: cache.hits,
    cacheMisses: cache.misses,
    cacheEntries: cache.size
  };
  const row: CompositionRow = {
    model: options.label,
    view: 'composition',
    engine: last.engine,
    source: `${options.root}::${options.composition}`,
    nodes: counts.visibleNodes,
    edges: counts.visibleEdges,
    width: round(last.composed.width, 2),
    height: round(last.composed.height, 2),
    iterations: options.iterations,
    stages: summarize(runs),
    fingerprint: compositionFingerprint(last.composed),
    quality: composedQuality(last.composed),
    counts,
    bytes: last.bytes,
    coldParseMs: round(coldParseMs, 3),
    commit: null,
    timestamp: new Date().toISOString()
  };
  return { row, composed: last.composed };
}

export interface CompositionStageDelta {
  stage: CompositionStage;
  baseline: number | null;
  current: number | null;
  delta: number | null;
}

export interface CompositionRowComparison {
  key: string;
  model: string;
  view: string;
  engine: string;
  status: 'compared' | 'added' | 'missing';
  fingerprintChanged: boolean;
  baselineFingerprint: string | null;
  fingerprint: string | null;
  stages: CompositionStageDelta[];
}

export interface CompositionComparison {
  rows: CompositionRowComparison[];
  geometryChanged: boolean;
}

/** Baseline comparison for composition rows, including the composition-only stages. */
export function compareCompositionRows(
  current: readonly CompositionRow[],
  baseline: readonly CompositionRow[]
): CompositionComparison {
  const baselineByKey = new Map(baseline.map((row) => [rowKey(row), row]));
  const rows: CompositionRowComparison[] = current.map((row) => {
    const previous = baselineByKey.get(rowKey(row));
    const stages: CompositionStageDelta[] = [];
    for (const stage of COMPOSITION_STAGES) {
      const before = previous?.stages[stage]?.p50 ?? null;
      const after = row.stages[stage]?.p50 ?? null;
      if (before === null && after === null) continue;
      stages.push({
        stage,
        baseline: before,
        current: after,
        delta: before === null || after === null ? null : round(after - before, 3)
      });
    }
    return {
      key: rowKey(row),
      model: row.model,
      view: row.view,
      engine: row.engine,
      status: previous ? 'compared' : 'added',
      fingerprintChanged: previous ? previous.fingerprint !== row.fingerprint : false,
      baselineFingerprint: previous?.fingerprint ?? null,
      fingerprint: row.fingerprint,
      stages
    };
  });
  const measured = new Set(current.map((row) => rowKey(row)));
  for (const row of baseline)
    if (!measured.has(rowKey(row)))
      rows.push({
        key: rowKey(row),
        model: row.model,
        view: row.view,
        engine: row.engine,
        status: 'missing',
        fingerprintChanged: false,
        baselineFingerprint: row.fingerprint,
        fingerprint: null,
        stages: []
      });
  return { rows, geometryChanged: rows.some((row) => row.fingerprintChanged) };
}
